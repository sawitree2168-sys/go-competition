-- Name for matching: no title in front (ด.ช./ด.ญ./นาย/นางสาว/น.ส./นาง), no spaces or invisible characters, lower case.
create or replace function gt_private.name_key_v1(p text) returns text
language sql immutable set search_path = pg_catalog as $$
  select lower(regexp_replace(regexp_replace(
           regexp_replace(btrim(regexp_replace(coalesce(p, ''), '[' || chr(160) || chr(8203) || '-' || chr(8205) || chr(65279) || ']', '', 'g')),
                          '^(ด\.ช\.|ด\.ญ\.|น\.ส\.|นางสาว\s|นาย\s|นาง\s)\s*', ''),
           '\s+', '', 'g'), '\.+$', ''))
$$;

